/*
    Константи контрбатарейного радара.

    Числа взяті з AN/TPQ-36: сектор 90 градусів, 18 км по артилерії й
    24 км по ракетах. У AN/TPQ-37 те саме працює на 3-50 км залежно від
    типу цілі, тож простір для налаштування — увесь.
*/

// Дальність виявлення за типом траєкторії, м
#define CBR_RANGE_MORTAR 15000
#define CBR_RANGE_GUN 18000
#define CBR_RANGE_ROCKET 24000

// Сектор огляду, градусів. Відлічується від НОСА машини, тож радар
// повертають, наводячи сектор на потрібний напрямок
#define CBR_SECTOR 90

/*
    Нижче цього кута кидання траєкторія настильна: снаряд не піднімається
    над променем радара, і той його не бачить. Саме тому контрбатарейний
    радар не реагує на танки й ПТУР, хоч ті й летять поруч.
*/
#define CBR_MIN_ELEV 15

/*
    Нижче цієї дульної швидкості постріл рахується мінометним, м/с.

    Саме швидкість, а НЕ кут кидання: кут залежить від дальності до
    цілі, і гаубиця на навісній траєкторії бере і 70 градусів — по куту
    вона щоразу вигляділа б мінометом. Швидкість же різниться кратно й
    від дальності майже не залежить: міномет це 150-300 м/с, ствольна
    артилерія 500-900.
*/
#define CBR_MORTAR_SPEED 350

/*
    Похибка зворотної екстраполяції, частка дальності. Радар рахує
    назад по КОРОТКІЙ ділянці дуги, і кутова помилка на ній
    перетворюється на лінійну пропорційно відстані: те саме кутове
    відхилення на 20 км дає вп'ятеро більший промах, ніж на 4 км.
*/
#define CBR_ERROR 0.004

#define CBR_MARKER_LIFE 300  // скільки живе позначка на карті, с
#define CBR_MERGE 250        // ближчі засічки — та сама вогнева позиція, м

// Повільніше — не балістична ціль (випав боєприпас, відділився блок)
#define CBR_MIN_SPEED 40

// Типи траєкторії: індекс у назвах і в дальностях
#define CBR_KIND_MORTAR 0
#define CBR_KIND_GUN 1
#define CBR_KIND_ROCKET 2

#define CBR_MARKER_TYPE "mil_triangle"
