// Константи контрбатарейного радара. Числа з AN/TPQ-36: сектор 90
// градусів, 18 км по артилерії й 24 по ракетах

// дальність одна на будь-який вогонь: три різні дуги на індикаторі
// довелося б або малювати, або усереднювати — і будь-яка збрехала б
#define CBR_RANGE 20000
#define CBR_SECTOR 90        // сектор огляду відносно носа машини, градусів

// нижче цього кута кидання траєкторія настильна й над променем не
// піднімається — тому танки й ПТУР для радара не існують
#define CBR_MIN_ELEV 15

/*
    Реєструється САМ СНАРЯД, а не знаряддя: батарея за хребтом невидима,
    поки снаряди не піднялись вище гребеня. Вирішує тут дальність САМОЇ
    СТРІЛЬБИ, а не відстань до гармати: вогонь накоротко закритий, на
    велику дальність видно, бо дуга вища. Звідси й вибір позиції: у
    секторі не має бути гребеня, вищого за десяток градусів.
*/
#define CBR_MAST 4           // антена над корпусом машини, м
#define CBR_ARC_DT 2         // крок відліку точок дуги під перевірку, с
#define CBR_LOS_STEP 150     // крок читання профілю рельєфу, м
#define CBR_LOS_MIN 8        // мінімум відліків: ближній пагорб інакше проскочив би

// Місцева завада: дах, бункер, ангар — карта висот про поставлені
// об'єкти не знає нічого. Промінь короткий навмисно: закриває антену те,
// що поруч, а двадцять кілометрів геометрії коштували б дорожче за все
#define CBR_CLEAR 60         // на скільки метрів довкола станції шукається завада
#define CBR_LOS_EVERY 0.5    // як часто перепитується видимість кожного снаряда, с

// біля землі промінь забиває власне відбиття від рельєфу
#define CBR_BEAM_MIN 3

// похибка зворотної екстраполяції, частка дальності: рахунок іде по
// короткій ділянці дуги, і кутова помилка росте в лінійну з відстанню
#define CBR_ERROR 0.04

// Кожен постріл із тієї самої позиції — ще один замір, і коло звужується
// до межі. Статистика дала б корінь із N, тобто сотню пострілів, а в Армі
// їх 20-30 на весь бій — тому крива стиснута під реальний наліт.
// Обидва числа налаштовуються модулем окремо на станцію
#define CBR_ERROR_MIN 30     // до скількох метрів звужується коло
#define CBR_ERROR_SHOTS 7    // за скільки пострілів воно туди доходить

// Штраф за ПІЗНЄ захоплення: назад станція рахує по непройденій ділянці
// підйому, і якщо снаряд узяли аж біля вершини, іти доводиться наосліп.
// Міряється часткою від вершини, а не метрами: висота захоплення сама
// росте з дальністю, і в метрах штраф повторив би дальність удруге
#define CBR_ERROR_LATE 2

// скільки станція мусить ВЕСТИ снаряд, щоб було з чого рахувати назад;
// решта затримки — уже рахунок, і видимість для нього не потрібна
#define CBR_TRACK_MIN 2

#define CBR_DELAY 5          // від пострілу до появи засічки, с

// Станція не гадає, куди снаряд упаде, — показує його там, де він зараз.
// Дуга рахується один раз, при захопленні, далі положення береться з неї
// за часом: мережею не ганяється нічого, кадр коштує одного множення
#define CBR_SIM_DT 0.25      // найбільший крок інтегрування дуги, с
#define CBR_SIM_STEPS 2000

// «Та сама вогнева» — це ще й той самий снаряд: танк і гаубиця з одного
// двору дають різні заміри. Допуск по швидкості потрібен реактивним:
// вона знімається після вигоряння й від пострілу до пострілу гуляє
#define CBR_MERGE 250        // ближчі засічки — та сама вогнева позиція, м
#define CBR_SAME_SPEED 0.15  // розбіг швидкості в межах однієї цілі, частка
#define CBR_ACQ_LIFE 900     // скільки засічка живе в журналі станції, с
#define CBR_ACQ_MAX 24       // глибина журналу: старіші витісняються
#define CBR_MIN_SPEED 40     // повільніше — не балістична ціль

#define CBR_MANNED_EVERY 10  // як часто сервер перевіряє перелік станцій, с

#define CBR_MARKER_TYPE "mil_triangle"
// прозора текстура лишає від виклику drawIcon самий підпис, без позначки
#define CBR_ICO_NONE "#(argb,8,8,3)color(0,0,0,0)"
#define CBR_ICO_STATION "\A3\ui_f\data\map\markers\nato\o_installation.paa"
#define CBR_ICO_SHELL "\A3\ui_f\data\map\markers\military\dot_CA.paa"

// чат, радіо й позначки мають спільну нумерацію каналів
#define CBR_CHAN_SIDE 1
