/*
    Константи контрбатарейного радара.

    Числа взяті з AN/TPQ-36: сектор 90 градусів, 18 км по артилерії й
    24 км по ракетах. У AN/TPQ-37 те саме працює на 3-50 км залежно від
    типу цілі, тож простір для налаштування — увесь.
*/

/*
    Дальність виявлення, м — одна на будь-який вогонь. У справжніх
    станцій вона різниться за типом цілі (в AN/TPQ-36 це 18 км по
    артилерії й 24 по ракетах), але на індикаторі тоді довелося б
    малювати три різні дуги або одну усереднену — і будь-яка з них
    брехала б. Одне число видно на екрані таким, яким воно є.
*/
#define CBR_RANGE 20000

// Сектор огляду, градусів. Відлічується від НОСА машини, тож радар
// повертають, наводячи сектор на потрібний напрямок
#define CBR_SECTOR 90

/*
    Нижче цього кута кидання траєкторія настильна: снаряд не піднімається
    над променем радара, і той його не бачить. Саме тому контрбатарейний
    радар не реагує на танки й ПТУР, хоч ті й летять поруч.
*/
#define CBR_MIN_ELEV 15

/*
    Похибка зворотної екстраполяції, частка дальності. Радар рахує
    назад по КОРОТКІЙ ділянці дуги, і кутова помилка на ній
    перетворюється на лінійну пропорційно відстані: те саме кутове
    відхилення на 20 км дає вп'ятеро більший промах, ніж на 4 км.
*/
#define CBR_ERROR 0.004

#define CBR_MERGE 250        // ближчі засічки — та сама вогнева позиція, м
#define CBR_ACQ_LIFE 900     // скільки засічка тримається в журналі станції, с
#define CBR_ACQ_MAX 24       // глибина журналу: старіші витісняються

// Повільніше — не балістична ціль (випав боєприпас, відділився блок)
#define CBR_MIN_SPEED 40

#define CBR_MARKER_TYPE "mil_triangle"

/*
    Консоль оператора. Макет 2560x1440 масштабується часткою safeZone —
    та сама розкладка за будь-якої роздільної здатності.
*/
#define CBR_UI_SCALE 1
#define CBR_LU (safeZoneH / 1440)
#define CBR_PH (CBR_LU * CBR_UI_SCALE)
#define CBR_PW (CBR_PH * pixelW / pixelH)
#define CBR_PXU (safeZoneW / 2560)

#define CBR_IDD 8451

// Люмінофор: усе однією фарбою, як на справжньому індикаторі
#define CBR_COL_BG [0.02, 0.04, 0.03, 0.94]
#define CBR_COL_PANEL [0.05, 0.09, 0.06, 0.85]
#define CBR_COL_MAIN [0.35, 0.95, 0.5, 0.9]
#define CBR_COL_DIM [0.35, 0.95, 0.5, 0.28]
#define CBR_COL_FAINT [0.35, 0.95, 0.5, 0.12]
// Обрана мітка — найпомітніша: саме з нею оператор зараз працює.
// Свіжа лише біла: вона привертає увагу, але вибір за людиною
#define CBR_COL_SEL [1, 0.6, 0.15, 1]
#define CBR_COL_HOT [1, 1, 1, 1]   // засічка молодша за CBR_HOT_AGE

#define CBR_HOT_AGE 45     // скільки секунд засічка вважається свіжою
#define CBR_SWEEP_PERIOD 2 // період проходу розгортки по сектору, с
// Крок дуг дальності, м. Саме КРОК, а не кількість: інакше при зміні
// дальності станції ціна поділки поїде, і засічки не зміряєш оком
#define CBR_RING_STEP 2500
#define CBR_ARC_STEP 5     // крок сегмента дуги, градусів
#define CBR_SLEW_STEP 5    // на скільки градусів крутить сектор одне натискання

// Розкладка в пікселях макета
#define CBR_UI_ROWS 12     // рядків у журналі
#define CBR_UI_ROW_H 34

/*
    Іконки й підписи на індикаторі. drawIcon міряє їх у ЧАСТКАХ ЕКРАНА,
    а не в метрах, і з масштабом карти вони не міняються — так і треба:
    підпис має лишатися читаним і на дальньому огляді, і зблизька.

    Числа тут абсолютні, бо одиниці розмітки (CBR_PW) для цього не
    годяться: вони на два порядки дрібніші, і підпис виходив таким, що
    його не прочитати.

    Ділення на getResolution#5 прибирає вплив налаштування розміру
    інтерфейсу — інакше в гравця з великим UI підпис лізе на пів екрана.
*/
#define CBR_UI_COEF (getResolution select 5)
#define CBR_ICON_SIZE (0.034 / CBR_UI_COEF)
#define CBR_TEXT_SIZE (0.028 / CBR_UI_COEF)
#define CBR_RING_TEXT (0.022 / CBR_UI_COEF)
